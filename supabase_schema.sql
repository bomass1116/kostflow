-- 1. Tabel Users (Pengguna & Hak Akses)
create table if not exists users (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password_hash text not null,
  role text not null,
  full_name text not null,
  phone text
);

-- 2. Tabel Settings (Pengaturan Kos)
create table if not exists settings (
  key text primary key,
  value text
);

-- 3. Tabel Rooms (Kamar)
create table if not exists rooms (
  id bigint generated by default as identity primary key,
  code text unique not null,
  type_name text not null,
  floor integer not null,
  size text,
  price integer not null,
  facilities text,
  description text,
  photo text,
  status text default 'Tersedia'
);

-- 4. Tabel Reservations (Reservasi Calon Penghuni)
create table if not exists reservations (
  id bigint generated by default as identity primary key,
  code text unique not null,
  room_id bigint references rooms(id),
  user_id bigint references users(id),
  name text not null,
  phone text,
  id_file text,
  proof_file text,
  deposit integer,
  start_date text,
  months integer,
  status text default 'Menunggu',
  reject_reason text,
  created_at text
);

-- 5. Tabel Contracts (Kontrak Sewa)
create table if not exists contracts (
  id bigint generated by default as identity primary key,
  tenant_id bigint references users(id),
  room_id bigint references rooms(id),
  start_date text,
  end_date text,
  rent integer,
  status text default 'Aktif'
);

-- 6. Tabel Invoices (Tagihan / Pembayaran)
create table if not exists invoices (
  id bigint generated by default as identity primary key,
  number text unique not null,
  contract_id bigint references contracts(id),
  tenant_id bigint references users(id),
  type text,
  description text,
  amount integer,
  due_date text,
  status text default 'Belum Dibayar',
  proof_file text,
  reject_reason text,
  ticket_id bigint,
  created_at text,
  paid_at text
);

-- 7. Tabel Ledger (Buku Kas)
create table if not exists ledger (
  id bigint generated by default as identity primary key,
  date text not null,
  kind text not null,
  category text not null,
  description text,
  amount integer not null,
  invoice_id bigint references invoices(id)
);

-- 8. Tabel Tickets (Keluhan / Permintaan)
create table if not exists tickets (
  id bigint generated by default as identity primary key,
  number text unique not null,
  tenant_id bigint references users(id),
  type text,
  category text,
  description text,
  photo text,
  priority text,
  status text default 'Baru',
  reject_reason text,
  schedule_note text,
  cost integer,
  rating integer,
  created_at text,
  updated_at text
);

-- 9. Tabel Notifications (Notifikasi)
create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id),
  message text not null,
  created_at text,
  is_read integer default 0
);

-- 10. Tabel Files (foto KTP, bukti transfer, foto kamar/keluhan) - disimpan di Supabase supaya
--     tidak hilang saat server aplikasi (Render) restart.
create table if not exists files (
  name       text primary key,
  content    bytea not null,
  created_at timestamptz default now()
);

-- ---------------------------------------------------------------------
-- TAMBAHAN 1: index supaya query cepat
-- ---------------------------------------------------------------------
create index if not exists idx_rooms_status       on rooms(status);
create index if not exists idx_contracts_tenant   on contracts(tenant_id, status);
create index if not exists idx_invoices_tenant    on invoices(tenant_id);
create index if not exists idx_invoices_status    on invoices(status);
create index if not exists idx_tickets_tenant     on tickets(tenant_id);
create index if not exists idx_notif_user         on notifications(user_id, is_read);

-- ---------------------------------------------------------------------
-- TAMBAHAN 2 (PENTING): kunci tabel dari akses publik lewat API Supabase.
-- Tanpa ini, siapa pun yang punya publishable/anon key bisa membaca tabel users
-- (termasuk hash password) dan mengubah data. Aplikasi KostFlow tetap jalan normal
-- karena memakai DATABASE_URL (role postgres, melewati RLS).
-- ---------------------------------------------------------------------
alter table users         enable row level security;
alter table settings      enable row level security;
alter table rooms         enable row level security;
alter table reservations  enable row level security;
alter table contracts     enable row level security;
alter table invoices      enable row level security;
alter table ledger        enable row level security;
alter table tickets       enable row level security;
alter table notifications enable row level security;
alter table files         enable row level security;
